# Gera um SQL com a estrutura REAL (lida do catálogo da base RH, só SELECT) de um conjunto de tabelas, para testar migrations em PGlite.
# Uso (da raiz do repo): python -I scripts/emylia/base-teste/gerar_base.py <saida.sql> tabela1 tabela2 ...
import json, subprocess, sys, re

WT = __import__("os").path.abspath(__import__("os").path.join(__import__("os").path.dirname(__file__), "..", "..", ".."))
NPX = ["npx.cmd", "--prefix", r"D:\Olyvia2.0-Documentacao", "supabase", "db", "query", "--linked", "--output-format", "json"]
out, tabs = sys.argv[1], sys.argv[2:]
lista = ",".join("'" + t + "'" for t in tabs)

def q(sql):
    r = subprocess.run(NPX + [" ".join(sql.split())], cwd=WT, capture_output=True, text=True, encoding="utf8")
    s = r.stdout
    if "\"rows\"" not in s: raise SystemExit("A consulta falhou: " + (s or r.stderr)[-400:])
    return json.loads(s[s.index("{"):])["rows"]

cols = q(f"""select c.relname t, a.attname col, format_type(a.atttypid,a.atttypmod) tipo, a.attnotnull nn, pg_get_expr(d.adbin,d.adrelid) def, a.attidentity ident, a.attgenerated ger,
  (select t2.typtype from pg_type t2 where t2.oid=a.atttypid) typtype, (select t2.typname from pg_type t2 where t2.oid=a.atttypid) typname
  from pg_class c join pg_namespace n on n.oid=c.relnamespace join pg_attribute a on a.attrelid=c.oid and a.attnum>0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid=c.oid and d.adnum=a.attnum where n.nspname='public' and c.relkind='r' and c.relname in ({lista}) order by c.relname, a.attnum""")
cons = q(f"""select c.relname t, k.conname nome, k.contype tipo, pg_get_constraintdef(k.oid) def, (select r.relname from pg_class r where r.oid=k.confrelid) ref
  from pg_constraint k join pg_class c on c.oid=k.conrelid join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relname in ({lista}) and k.contype in ('p','u','c','f')""")
enums = sorted({c["typname"] for c in cols if c["typtype"] == "e"})
labels = q("select t.typname n, string_agg(quote_literal(e.enumlabel), ',' order by e.enumsortorder) l from pg_type t join pg_enum e on e.enumtypid=t.oid where t.typname in (" + ",".join("'" + e + "'" for e in enums) + ") group by 1") if enums else []

L = []
for e in labels:
    L.append(f"CREATE TYPE public.{e['n']} AS ENUM ({e['l']});")
por = {}
for c in cols:
    por.setdefault(c["t"], []).append(c)
for t, cs in por.items():
    defs = []
    for c in cs:
        s = f'"{c["col"]}" {c["tipo"]}'
        if c["ident"] in ("a", "d"):
            s += " GENERATED BY DEFAULT AS IDENTITY"
        elif c["def"] is not None and c["ger"] != "s" and "nextval" not in c["def"]:
            s += f" DEFAULT {c['def']}"
        if c["nn"]:
            s += " NOT NULL"
        defs.append(s)
    L.append(f"CREATE TABLE public.{t} (\n  " + ",\n  ".join(defs) + "\n);")
ordem = {"p": 0, "u": 1, "c": 2, "f": 3}
for k in sorted(cons, key=lambda k: ordem[k["tipo"]]):
    if k["tipo"] == "f" and k["ref"] not in tabs:
        continue  # chave para uma tabela que não está no teste
    if k["tipo"] == "c" and re.search(r"\b[a-z_]+\(", k["def"].replace("ANY (", "").replace("ARRAY[", "")) and not re.search(r"\b(length|btrim|lower|upper|char_length|array_length|cardinality|now)\(", k["def"]):
        L.append(f"-- (fora) {k['t']}.{k['nome']}: {k['def'][:100]}")
        continue
    L.append(f"ALTER TABLE public.{k['t']} ADD CONSTRAINT \"{k['nome']}\" {k['def']};")
open(out, "w", encoding="utf8").write("\n".join(L) + "\n")
print("escrito", out, len(por), "tabelas,", len(cons), "restrições,", len(labels), "tipos")
