import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { cleanup, fireEvent, render, screen } from "@testing-library/react";
import { LanguageProvider } from "@/contexts/LanguageContext";
import { TemplateDocSettingsPanel, type TemplateDocSettings } from "../../TemplateDocSettingsPanel";

vi.mock("@/integrations/supabase/client", () => ({ supabase: {} }));
vi.mock("@/contexts/CompanyContext", () => ({ useCompany: () => ({ activeCompany: { id: "org-teste", name: "Org de teste" } }) }));
vi.mock("@/components/contracts/useOrgHeaderData", () => ({ useOrgHeaderData: () => ({ data: null }) }));

const VALOR: TemplateDocSettings = {
  header_style: "split",
  primary_color: "#112233",
  show_footer: true,
  show_quote_items: true,
  contract_block_title: "",
  contract_block_subtitle: "www.exemplo.pt",
  footer_text: "",
  quote_items_title: "",
};

function montar(props: Partial<React.ComponentProps<typeof TemplateDocSettingsPanel>> = {}) {
  localStorage.setItem("language", "pt");
  const onChange = vi.fn();
  const r = render(
    <LanguageProvider>
      <TemplateDocSettingsPanel value={VALOR} onChange={onChange} {...props} />
    </LanguageProvider>,
  );
  return { ...r, onChange };
}

const EN = { codigo: "en", base: "pt", textoBase: "Documento gerado pelo Olyvia" };

beforeEach(() => localStorage.clear());
afterEach(cleanup);

describe("TemplateDocSettingsPanel no idioma base (sem versão): nada muda", () => {
  it("não acrescenta nenhum fieldset nem nota, e os campos estão ativos", () => {
    const { container } = montar({ value: { ...VALOR, contract_block_title: "CONTRATO", footer_text: "Rodapé" } });
    expect(container.querySelector("fieldset")).toBeNull();
    expect(screen.queryByText(/Comum a todos os idiomas/)).toBeNull();
    for (const el of screen.getAllByDisplayValue("#112233")) expect(el).toBeEnabled();
    expect(screen.getByRole("switch", { name: /Mostrar rodapé/ })).toBeEnabled();
    expect(screen.getByLabelText("Título da secção")).toBeEnabled();
  });

  it("os textos do cabeçalho continuam sem sugestão própria", () => {
    montar({ value: { ...VALOR, contract_block_title: "CONTRATO" } });
    expect(screen.queryByPlaceholderText("CONTRACT")).toBeNull();
    expect(screen.getByPlaceholderText("Artigos do Orçamento")).toBeInTheDocument();
  });
});

describe("TemplateDocSettingsPanel numa versão de idioma", () => {
  it("cores, margens e interruptores ficam desativados, com a nota «comum a todos os idiomas»", () => {
    montar({ versao: EN });
    for (const el of screen.getAllByDisplayValue("#112233")) expect(el).toBeDisabled();
    expect(screen.getByRole("switch", { name: /Mostrar rodapé/ })).toBeDisabled();
    expect(screen.getAllByText("Comum a todos os idiomas — altere na versão em Português.").length).toBeGreaterThanOrEqual(4);
  });

  it("o título do bloco do contrato fica editável, com a sugestão no idioma", () => {
    const { onChange } = montar({ versao: EN });
    const titulo = screen.getByPlaceholderText("CONTRACT");
    expect(titulo).toBeEnabled();
    fireEvent.change(titulo, { target: { value: "SERVICES AGREEMENT" } });
    expect(onChange).toHaveBeenLastCalledWith(expect.objectContaining({ contract_block_title: "SERVICES AGREEMENT", primary_color: "#112233" }));
    expect(screen.getByPlaceholderText("CONTRACT No.")).toBeEnabled();
    expect(screen.getByPlaceholderText("Date:")).toBeEnabled();
    expect(screen.getByPlaceholderText("Sales rep:")).toBeEnabled();
  });

  it("as variáveis e os interruptores do bloco do contrato são comuns (desativados)", () => {
    montar({ versao: EN });
    expect(screen.getByDisplayValue("{{contrato_numero}}")).toBeDisabled();
    expect(screen.getByDisplayValue("{{data}}")).toBeDisabled();
    expect(screen.getByDisplayValue("{{comercial_nome}}")).toBeDisabled();
  });

  it("o texto do rodapé é editável, com o texto base como sugestão e o aviso de fallback", () => {
    const { onChange } = montar({ versao: EN });
    const rodape = screen.getByPlaceholderText("Documento gerado pelo Olyvia");
    expect(rodape).toBeEnabled();
    expect(screen.getByText("Sem texto neste idioma: usa-se o texto em Português.")).toBeInTheDocument();
    fireEvent.change(rodape, { target: { value: "Generated by Olyvia" } });
    expect(onChange).toHaveBeenLastCalledWith(expect.objectContaining({ footer_text: "Generated by Olyvia" }));
  });

  it("com texto no rodapé da versão o aviso de fallback desaparece", () => {
    montar({ versao: EN, value: { ...VALOR, footer_text: "Generated by Olyvia" } });
    expect(screen.queryByText(/Sem texto neste idioma/)).toBeNull();
  });

  it("o título da tabela é editável (com sugestão no idioma) e o resto da lista de artigos é comum", () => {
    const { onChange } = montar({ versao: EN });
    const titulo = screen.getByLabelText("Título da secção");
    expect(titulo).toBeEnabled();
    expect(titulo).toHaveAttribute("placeholder", "Quote items");
    fireEvent.change(titulo, { target: { value: "Items" } });
    expect(onChange).toHaveBeenLastCalledWith(expect.objectContaining({ quote_items_title: "Items" }));
    expect(screen.getByRole("switch", { name: "Lista de Artigos" })).toBeDisabled();
  });

  it("o subtítulo do bloco continua editável", () => {
    montar({ versao: EN });
    expect(screen.getByDisplayValue("www.exemplo.pt")).toBeEnabled();
  });
});
