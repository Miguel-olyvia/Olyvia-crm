import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { cleanup, fireEvent, render, screen, within } from "@testing-library/react";
import { LanguageProvider } from "@/contexts/LanguageContext";
import { ListaDeVerificacaoDaVersao } from "../ListaDeVerificacaoDaVersao";
import type { LinhaDeVerificacao } from "../versoesDoTemplate";

const LINHAS: LinhaDeVerificacao[] = [
  { chave: "corpo", estado: "igual", textoBase: "Entre as partes é celebrado este contrato.", textoVersao: "Entre as partes é celebrado este contrato.", pendentes: 1 },
  { chave: "titulo_cabecalho", estado: "falta", textoBase: "CONTRATO", textoVersao: "", pendentes: 1 },
  { chave: "rodape", estado: "traduzido", textoBase: "Documento gerado pelo Olyvia", textoVersao: "Generated by Olyvia", pendentes: 0 },
  { chave: "tabela", estado: "traduzido", textoBase: "Artigos do Orçamento", textoVersao: "Quote items", pendentes: 0 },
  { chave: "rotulos", estado: "falta", textoBase: "CONTRATO Nº · Data:", textoVersao: "", pendentes: 2 },
];

function montar(linhas: LinhaDeVerificacao[], lingua: "pt" | "en" = "pt") {
  localStorage.setItem("language", lingua);
  return render(<LanguageProvider><ListaDeVerificacaoDaVersao linhas={linhas} base="pt" /></LanguageProvider>);
}

beforeEach(() => localStorage.clear());
afterEach(cleanup);

describe("ListaDeVerificacaoDaVersao", () => {
  it("não mostra nada sem linhas (idioma base)", () => {
    const { container } = montar([]);
    expect(container.textContent).toBe("");
  });

  it("lista cada texto com o estado escrito por extenso (não só por cor)", () => {
    montar(LINHAS);
    const regiao = screen.getByRole("region", { name: "O que falta traduzir" });
    const itens = within(regiao).getAllByRole("listitem").map((li) => li.textContent?.replace(/\s+/g, " ").trim());
    expect(itens).toEqual([
      "Corpo da minuta Igual ao português",
      "Título do cabeçalho Em falta",
      "Rodapé Traduzido",
      "Título da tabela de artigos Traduzido",
      "Outros rótulos do cabeçalho (2) Em falta",
    ]);
  });

  it("o texto em português começa escondido e abre e fecha num painel recolhível", () => {
    montar(LINHAS);
    const botao = screen.getByRole("button", { name: "Mostrar o texto em português" });
    expect(botao).toHaveAttribute("aria-expanded", "false");
    expect(screen.queryByText("CONTRATO")).toBeNull();

    fireEvent.click(botao);
    expect(screen.getByRole("button", { name: "Esconder o texto em português" })).toHaveAttribute("aria-expanded", "true");
    const original = screen.getByText("CONTRATO");
    expect(original).toHaveAttribute("lang", "pt");
    expect(screen.getByText("Entre as partes é celebrado este contrato.", { selector: "[lang]" })).toBeInTheDocument();

    fireEvent.click(screen.getByRole("button", { name: "Esconder o texto em português" }));
    expect(screen.queryByText("CONTRATO")).toBeNull();
  });

  it("tudo traduzido diz-o", () => {
    montar(LINHAS.filter((l) => l.estado === "traduzido"));
    expect(screen.getByText("Está tudo traduzido.")).toBeInTheDocument();
  });

  it("com pendentes não mostra a mensagem de tudo traduzido", () => {
    montar(LINHAS);
    expect(screen.queryByText("Está tudo traduzido.")).toBeNull();
  });

  it("em inglês os textos mudam de língua", () => {
    montar(LINHAS, "en");
    expect(screen.getByRole("region", { name: "What is left to translate" })).toBeInTheDocument();
    expect(screen.getByRole("button", { name: "Show the Portuguese text" })).toBeInTheDocument();
    expect(screen.getAllByText("Missing").length).toBeGreaterThan(0);
  });

  it("o botão de recolher tem alvo de 44px", () => {
    montar(LINHAS);
    expect(screen.getByRole("button", { name: /Mostrar o texto/ }).className).toContain("min-h-11");
  });
});
