// Regras da lista de encomendas a fornecedor (Compras › Encomendas), ao estilo
// do protótipo (po.ts: poOpen/poLate) mas sobre as colunas reais de
// purchase_orders. Sem React, sem BD.

/** Estados "em aberto" (encomendada ou parcialmente recebida) — como poOpen do protótipo. */
export const PO_OPEN_STATUSES = ["ordered", "partially_received"] as const;

export const isPoOpenStatus = (status: string | null | undefined): boolean =>
  status === "ordered" || status === "partially_received";

/** Hoje em "YYYY-MM-DD" (hora local), comparável com as colunas date. */
export function todayIsoLocal(now: Date = new Date()): string {
  const y = now.getFullYear();
  const m = String(now.getMonth() + 1).padStart(2, "0");
  const d = String(now.getDate()).padStart(2, "0");
  return `${y}-${m}-${d}`;
}

/** Em aberto com a entrega prevista ultrapassada (poLate do protótipo). */
export function isPoLate(
  order: { status: string | null; expected_delivery: string | null; deleted_at?: string | null },
  today: string = todayIsoLocal(),
): boolean {
  if (order.deleted_at) return false;
  if (!isPoOpenStatus(order.status) || !order.expected_delivery) return false;
  return order.expected_delivery.slice(0, 10) < today;
}

/** Dias inteiros entre a entrega prevista e hoje (só faz sentido se atrasada). */
export function poDaysLate(expectedDelivery: string, today: string = todayIsoLocal()): number {
  const a = Date.parse(`${expectedDelivery.slice(0, 10)}T00:00:00Z`);
  const b = Date.parse(`${today}T00:00:00Z`);
  if (Number.isNaN(a) || Number.isNaN(b)) return 0;
  return Math.max(0, Math.round((b - a) / 86_400_000));
}

/**
 * Gerada automaticamente (rascunho criado pelos gatilhos das Encomendas
 * Clientes / contratos / vendas diretas): os gatilhos escrevem sempre a nota
 * "Gerada automaticamente a partir de…" (ver migrations fn_contract_supplier_request).
 */
export const isPoAutoGenerated = (order: { source_type?: string | null; notes?: string | null }): boolean =>
  order.source_type === "contract" && /^gerada automaticamente/i.test((order.notes ?? "").trim());

const EUR = new Intl.NumberFormat("pt-PT", { style: "currency", currency: "EUR" });
export const formatEur = (value: number | null | undefined): string => EUR.format(Number(value) || 0);
